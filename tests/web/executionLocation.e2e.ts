  await catalogStarted;await tab.getByRole('link',{name:'Workspaces',exact:true}).click();releaseCatalog();
  const abandoned=await delayed;assert(abandoned!==null&&typeof abandoned==='object'&&'status'in abandoned);assert.equal(abandoned.status,'unavailable');assert.equal(new URL(tab.url()).hash,'#/workspaces');
  const opened=await tab.evaluate(`import('/assets/navigation-broker.js').then(({navigation})=>navigation.openFeature('execution',{kind:'repository-jobs',controllerKey:'remote',projectId:'non-git',repositoryId:'workspace'}))`);
  assert(opened!==null&&typeof opened==='object'&&'status'in opened);assert.equal(opened.status,'opened');assert.equal(new URL(tab.url()).hash,'#/features/execution/controllers/remote/jobs');
  await tab.close();
  process.stdout.write('Execution real-location controller authority, Back/Forward, unavailable targets, list return, held-detail fencing and hidden-mount recovery passed.\n');
