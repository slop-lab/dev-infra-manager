import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import {createNonGitWorkbench} from './non-git-workbench/harness.js';
const executablePath = process.env.DIM_CHROMIUM;
if (!executablePath) throw new Error('DIM_CHROMIUM is required');
const fixture = await createNonGitWorkbench(), browser = await chromium.launch({executablePath,headless:true});
const page = await browser.newPage();
let routeCreates = 0, serverStops = 0;
page.on('request', (request) => { if(request.url().endsWith('/operations/routes.create')) routeCreates++; if(request.url().endsWith('/operations/server.stop')) serverStops++; });
try {
  await page.goto(`${fixture.origin}/#/workspaces/local/17094660-a627-4a17-acd2-6418c0b79967/routes`);
  await page.getByLabel('Username',{exact:true}).fill(fixture.username); await page.getByLabel('Password',{exact:true}).fill(fixture.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  const row = page.locator('.workspace-row:visible'), form = row.getByRole('form',{name:'Create route for studio',exact:true});
  await form.getByLabel('Route name',{exact:true}).fill('phase-recovery'); await form.getByLabel('Service port',{exact:true}).fill('8000');
  await page.route('**/operations/routes.create',async(route)=>{await route.fetch(); await route.fulfill({status:503,json:{error:'synthetic lost response'}});},{times:1});
  await form.getByRole('button',{name:'Create route',exact:true}).click();
  await row.getByText(/^Route change outcome is unknown/).waitFor();
  await row.getByRole('button',{name:'stop studio',exact:true}).click();
  await row.getByRole('button',{name:'start studio',exact:true}).waitFor();
  assert.equal(await form.getByLabel('Route name',{exact:true}).inputValue(),'phase-recovery');
  assert.equal(await form.getByRole('button',{name:'Create route',exact:true}).isDisabled(),true);
  await row.getByRole('button',{name:'start studio',exact:true}).click();
  await row.getByRole('button',{name:'stop studio',exact:true}).waitFor();
  assert.equal(await form.getByLabel('Service port',{exact:true}).inputValue(),'8000');
  assert.equal(await form.getByRole('button',{name:'Create route',exact:true}).isDisabled(),true);
  assert.equal(routeCreates,1);
  await row.getByRole('button',{name:'Refresh routes',exact:true}).click();
  await row.getByText('Awaiting operator approval. This route is not available yet.',{exact:true}).waitFor();
  assert.equal(routeCreates,1);
  await row.getByRole('link',{name:'Tools',exact:true}).click();
  await row.getByRole('button',{name:'Stop OpenCode server',exact:true}).waitFor();
  await page.route('**/operations/server.stop',async(route)=>{await route.fetch();await route.fulfill({status:503,json:{error:'synthetic lost response'}});},{times:1});
  await row.getByRole('button',{name:'Stop OpenCode server',exact:true}).click();
  await row.getByText(/^Stop OpenCode server: outcome is unknown/).waitFor();
  await row.getByRole('button',{name:'stop studio',exact:true}).click();
  await row.getByRole('button',{name:'start studio',exact:true}).waitFor();
  await row.getByRole('button',{name:'start studio',exact:true}).click();
  await row.getByRole('button',{name:'stop studio',exact:true}).waitFor();
  assert.equal(serverStops,1);
  assert.equal(await row.getByRole('button',{name:'Stop OpenCode server',exact:true}).isDisabled(),true);
  await row.getByRole('button',{name:'Retry workspace tools',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(button=>button.textContent==='Start OpenCode server'&&!button.disabled));
  assert.equal(serverStops,1);
  process.stdout.write('Workspace phase changes retain route drafts, route/tool unknown-write locks and explicit post-phase reconciliation without duplicate writes.\n');
} finally {await browser.close();await fixture.close();}
