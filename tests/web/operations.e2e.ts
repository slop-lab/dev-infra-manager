import assert from "node:assert/strict";
import { chromium } from "playwright-core";
import { createOperationsBrowserFixture } from "./operationsBrowserFixture.js";
const executablePath = process.env.DIM_CHROMIUM;
if (!executablePath) throw new Error("DIM_CHROMIUM must select the reviewed Chromium executable");
const fixture = await createOperationsBrowserFixture();
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage();
const errors: string[] = [];
page.on("pageerror", (error) => errors.push(error.message));
try {
  await page.goto(fixture.origin.replace("127.0.0.1", "localhost"));
  await page.getByLabel("Username").fill(fixture.username);
  await page.getByLabel("Password").fill(fixture.password);
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.locator("#login-error").getByText(`Open this console at ${fixture.origin} and sign in again. The address must match the configured public URL.`, { exact: true }).waitFor();
  assert.equal(await page.getByLabel("Username").getAttribute("aria-invalid"), "false");
  assert.equal(await page.getByLabel("Password").getAttribute("aria-invalid"), "false");
  await page.goto(fixture.origin);
  await page.getByLabel("Username").fill(fixture.username);
  await page.getByLabel("Password").fill(fixture.password);
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.locator("#operations-panel").waitFor({ state: "visible" });
  await page.getByText("Workspaces refreshed.", { exact: true }).waitFor();
  const incomplete = page.locator(".workspace-row").filter({ has: page.getByRole("heading", { name: "incomplete", exact: true }) });
  await incomplete.getByText(/Initial setup did not finish/).waitFor();
  assert.match(await incomplete.innerText(), /image is unavailable/);
  assert.doesNotMatch(await incomplete.innerText(), /PRIVATE_SECRET|\/private\/host\/path/);
  assert.equal(await incomplete.getByRole("button", { name: "start incomplete", exact: true }).isVisible(), false);
  assert.equal(await page.locator("#feature-navigation").isHidden(), true);
  const newWorkspace = page.getByRole("form", { name: "New workspace on devbox", exact: true });
  assert.equal(await newWorkspace.isVisible(), false);
  await page.getByRole("button", { name: "New workspace on devbox", exact: true }).click();
  await newWorkspace.waitFor({ state: "visible" });
  await newWorkspace.getByLabel("Git URL or dim://PROJECT on devbox", { exact: true }).fill("https://example.test/daily.git");
  assert.equal(await newWorkspace.getByLabel("Workspace name on devbox", { exact: true }).inputValue(), "daily");
  await newWorkspace.getByLabel("Workspace name on devbox", { exact: true }).fill("browser-created");
  await newWorkspace.getByLabel("Git URL or dim://PROJECT on devbox", { exact: true }).fill("https://example.test/another.git");
  assert.equal(await newWorkspace.getByLabel("Workspace name on devbox", { exact: true }).inputValue(), "browser-created");
  await newWorkspace.getByLabel("Git URL or dim://PROJECT on devbox", { exact: true }).fill("https://example.test/daily.git");
  await newWorkspace.getByText("Advanced options", { exact: true }).click();
  await newWorkspace.getByLabel("Runtime on devbox", { exact: true }).fill("container");
  await newWorkspace.getByLabel("Image (optional) on devbox", { exact: true }).fill("registry.example.test/dev:reviewed");
  await newWorkspace.getByLabel("CPU limit (optional) on devbox", { exact: true }).fill("1.5");
  const development = page.locator(".workspace-row").filter({ has: page.getByRole("heading", { name: "development", exact: true }) });
  await development.getByText("Settings for development", { exact: true }).click();
  await development.getByLabel("CPUs for development", { exact: true }).fill("0.75");
  await development.getByLabel("Memory for development", { exact: true }).fill("3g");
  await newWorkspace.getByRole("button", { name: "Cancel new workspace on devbox", exact: true }).click();
  assert.equal(await newWorkspace.isVisible(), false);
  await page.getByRole("button", { name: "New workspace on devbox", exact: true }).click();
  assert.equal(await newWorkspace.getByLabel("Git URL or dim://PROJECT on devbox", { exact: true }).evaluate((field) => field === document.activeElement), true);
  assert.equal(await newWorkspace.getByLabel("Workspace name on devbox", { exact: true }).inputValue(), "browser-created");
  await page.getByRole("button", { name: "Refresh services", exact: true }).click();
  await page.getByText("Workspaces refreshed.", { exact: true }).waitFor();
  assert.equal(await newWorkspace.getByLabel("Workspace name on devbox", { exact: true }).inputValue(), "browser-created");
  assert.equal(await development.getByLabel("CPUs for development", { exact: true }).inputValue(), "0.75");
  await development.getByRole("button", { name: "stop development", exact: true }).click();
  await development.getByRole("button", { name: "start development", exact: true }).waitFor();
  assert.equal((await fixture.workspace()).phase, "stopped");
  assert.equal(await development.getByLabel("CPUs for development", { exact: true }).inputValue(), "0.75");
  assert.equal(await newWorkspace.getByLabel("Git URL or dim://PROJECT on devbox", { exact: true }).inputValue(), "https://example.test/daily.git");
  assert.equal(await development.getByLabel("Memory for development", { exact: true }).inputValue(), "3g");
  assert.equal(await development.locator(".workspace-settings").evaluate((details) => details instanceof HTMLDetailsElement && details.open), true);
  await development.getByRole("button", { name: "Apply resources for development", exact: true }).click();
  await development.getByText("development: resource limits refreshed from the host.", { exact: true }).waitFor();
  assert.deepEqual((await fixture.workspace()).resources, { cpuCount: "0.75", memory: "3g", pidsLimit: "512" });
  await fixture.failNextCreate();
  await newWorkspace.getByRole("button", { name: "Create workspace on devbox", exact: true }).click();
  await newWorkspace.getByText(/Could not create browser-created on devbox/).waitFor();
  await newWorkspace.getByText(/The workspace image is unavailable on this host/).waitFor();
  assert.doesNotMatch(await newWorkspace.innerText(), /PRIVATE_SECRET|\/private\/host\/path/);
  assert.equal(await newWorkspace.getByLabel("Workspace name on devbox", { exact: true }).inputValue(), "browser-created");
  await newWorkspace.getByRole("button", { name: "Create workspace on devbox", exact: true }).click();
  const createdRow = page.locator(".workspace-row").filter({ has: page.getByRole("heading", { name: "browser-created", exact: true }) });
  await createdRow.waitFor();
  await newWorkspace.getByText(/host accepted browser-created.*listed below/i).waitFor();
  await newWorkspace.getByLabel("Git URL or dim://PROJECT on devbox", { exact: true }).fill("dim://next-project");
  assert.equal(await newWorkspace.getByLabel("Workspace name on devbox", { exact: true }).inputValue(), "next-project");
  const created = await fixture.createdWorkspace(); assert(created);
  assert.equal(created.source, "https://example.test/daily.git"); assert.equal(created.runtime, "container");
  assert.equal(created.image, "registry.example.test/dev:reviewed"); assert.equal(created.resources.cpuCount, "1.5");
  await createdRow.getByText("Settings for browser-created", { exact: true }).click();
  await createdRow.getByRole("button", { name: "discard browser-created", exact: true }).click();
  await createdRow.getByRole("button", { name: "Discard browser-created and its data", exact: true }).waitFor();
  await createdRow.getByRole("button", { name: "Keep browser-created", exact: true }).click();
  assert.equal((await fixture.actions()).includes("discard"), false);
  assert.equal(await createdRow.getByRole("button", { name: "Discard browser-created and its data", exact: true }).count(), 0);
  assert.doesNotMatch(await page.locator("#operations-message").innerText(), /Updated\./);
  await fixture.failNextList();
  await page.getByRole("button", { name: "Refresh services", exact: true }).click();
  const retryWorkspaces = page.getByRole("button", { name: "Retry workspaces on devbox", exact: true });
  await retryWorkspaces.click();
  await retryWorkspaces.waitFor({ state: "hidden" });
  await createdRow.waitFor();
  assert.equal(await development.getByRole("button", { name: "start development", exact: true }).isVisible(), true);
  await page.getByRole("button", { name: "Sign out" }).click();
  await page.locator("#login-view").waitFor({ state: "visible" });
  assert.equal(await page.locator("#operations-panel").isHidden(), true);
  await page.getByLabel("Username").fill("readonly");
  await page.getByLabel("Password").fill(fixture.password);
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByText("Workspaces refreshed.", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Create workspace on devbox", exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: "stop development", exact: true }).count(), 0);
  await fixture.clearWorkspaces();
  await page.getByRole("button", { name: "Refresh services", exact: true }).click();
  await page.getByText("No workspaces yet", { exact: true }).waitFor();
  assert.equal(await page.locator(".workspace-row").count(), 0);
  assert.equal(await page.getByRole("button", { name: "New workspace on devbox", exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log("operations-browser: workspace draft preservation, create failure/retry, safe discard cancellation, host recovery and logout PASS");
} finally { await browser.close(); await fixture.close(); }
